import { afterEach, expect, test } from "bun:test";
import { groundFindings, locate, needle, sideLines } from "../src/agents/pr_assistant/review-grounding.ts";
import { mergeBaseSha, prSections, refine } from "../src/agents/pr_assistant/review-refine.ts";
import { planPackages, riskRank, skipReason, skippedNote, splitUnit } from "../src/agents/pr_assistant/review-triage.ts";
import { APPROVE, REQUEST_CHANGES, decide, mkFinding, mkVerdict, parseReview } from "../src/agents/pr_assistant/review-verdict.ts";
import { applyVerification, excerpt, parseVerification, verifyFindings, verifyPrompt } from "../src/agents/pr_assistant/review-verify.ts";

const saved = { ...process.env };
afterEach(() => { for (const k of Object.keys(process.env)) if (!(k in saved)) delete process.env[k]; Object.assign(process.env, saved); });

const SECTION = "diff --git a/src/pay.ts b/src/pay.ts\n--- a/src/pay.ts\n+++ b/src/pay.ts\n@@ -10,4 +10,5 @@ export function charge() {\n   const total = sum(items);\n-  return total / count;\n+  const avg = total / count;\n+  return   avg.toFixed(2);\n   // done\n }\n";
const sections = { "src/pay.ts": SECTION };
const pr = { number: 7, title: "t", head: { sha: "h".repeat(40) }, base: { ref: "main", sha: "b".repeat(40), repo: { full_name: "o/r" } } } as any;

// --- triage ---------------------------------------------------------------
test("triage: generated, lock, binary and deleted files are skipped; real code is not", () => {
  expect(skipReason("app/test/auth_test.mocks.dart", "")).toBe("gerado");
  expect(skipReason("lib/router.g.dart", "")).toBe("gerado");
  expect(skipReason("web/package-lock.json", "")).toBe("lockfile");
  expect(skipReason("a.png", "Binary files a/a.png and b/a.png differ\n")).toBe("binário");
  expect(skipReason("old.ts", "diff --git a/old.ts b/old.ts\ndeleted file mode 100644\n")).toBe("removido");
  expect(skipReason("api/client.go", "+// Code generated by protoc-gen-go. DO NOT EDIT.\n")).toBe("gerado");
  expect(skipReason("src/pay.ts", SECTION)).toBe("");
  expect(skipReason("docker/build.sh", "+echo hi\n")).toBe("");
});
test("triage: runtime code is reviewed before config, tests and docs", () => {
  expect([".github/workflows/ci.yml", "src/a.ts", "package.json", "tests/a.test.ts", "README.md", "docker/run.sh"].map(riskRank)).toEqual([0, 0, 1, 2, 3, 0]);
  const plan = planPackages({ "README.md": "+doc\n", "tests/a.test.ts": "+t\n", "bun.lock": "+l\n", "x.mocks.dart": "+m\n", "src/a.ts": "+code\n" }, 10_000);
  expect(plan.packages.flat().map((u) => u.path)).toEqual(["src/a.ts", "tests/a.test.ts", "README.md"]);
  expect(skippedNote(plan.skipped)).toBe("1 lockfile, 1 gerado");
});
test("triage: a file bigger than the budget is split with correct line numbers instead of truncated", () => {
  const body = Array.from({ length: 60 }, (_, i) => `+line number ${i + 1}\n`).join("");
  const text = `diff --git a/big.ts b/big.ts\n--- /dev/null\n+++ b/big.ts\n@@ -0,0 +1,60 @@\n${body}`;
  const units = splitUnit("big.ts", text, 400);
  expect(units.length).toBeGreaterThan(3);
  expect(units.every((u) => u.text.length <= 400 + 40 && u.text.startsWith("diff --git a/big.ts"))).toBe(true);
  // every line survives, and each part resolves to the real new-side line number
  const all = new Map(units.flatMap((u) => [...sideLines(u.text).added]));
  expect(all.size).toBe(60);
  for (const [no, t] of all) expect(t).toBe(`line number ${no}`);
  expect(splitUnit("s.ts", "small", 400)).toHaveLength(1);
});

// --- grounding ------------------------------------------------------------
test("grounding: needle ignores diff markers, pasted line numbers and trivial quotes", () => {
  expect(needle("+  return   avg.toFixed(2);")).toBe("return avg.toFixed(2);");
  expect(needle("13: return avg.toFixed(2);")).toBe("return avg.toFixed(2);");
  expect(needle("}")).toBe(""); expect(needle(undefined)).toBe("");
  expect(locate("@@ -1 +1,2 @@\n 1\n+bug\n+debug bug here", "bug")).toBe(2); // a short quote only matches a whole line
  expect(locate(SECTION, "return avg.toFixed(2);")).toBe(12);
  expect(locate(SECTION, "return total / count;")).toBe(0);
  expect(locate(SECTION, "password: admin123")).toBe(-1);
});
test("grounding: the line comes from the quoted code, not from the model", () => {
  const g = groundFindings([mkFinding({ file: "b/src/pay.ts", line: 300, severity: "error", issue: "divide by zero", evidence: "const avg = total / count;" })], sections);
  expect(g.findings).toEqual([expect.objectContaining({ file: "src/pay.ts", line: 11, severity: "error" })]);
});
test("grounding: invented evidence and files outside the PR are dropped", () => {
  const g = groundFindings([
    mkFinding({ file: "src/pay.ts", line: 1, severity: "error", issue: "Credenciais expostas", evidence: "password: admin123" }),
    mkFinding({ file: "core/round_director.sma", severity: "error", issue: "plugin removido" }),
    mkFinding({ file: "(descrição do PR)", severity: "warn", issue: "sem evidências" }),
    mkFinding({ file: "src/pay.ts", issue: "  " }),
  ], sections);
  expect(g.findings.map((f) => f.file)).toEqual(["(descrição do PR)"]);
  expect(g.dropped.map((d) => d.reason)).toEqual(["evidência não existe no código", "arquivo fora do PR"]);
});
test("grounding: error without a quote is capped at warn; a quote found only in the clone still counts", () => {
  const g = groundFindings([mkFinding({ file: "src/pay.ts", line: 11, severity: "error", issue: "vague" })], sections);
  expect(g.findings[0]!.severity).toBe("warn");
  const read = (p: string) => (p === "src/caller.ts" ? "import x\ncharge(undefined as any);\n" : null);
  const far = groundFindings([mkFinding({ file: "src/caller.ts", severity: "error", issue: "caller breaks", evidence: "charge(undefined as any);" })], sections, read);
  expect(far.findings).toEqual([expect.objectContaining({ file: "src/caller.ts", line: 2, severity: "error" })]);
});

// --- verification ---------------------------------------------------------
test("verify: prompt shows the real code, results refute/downgrade but never raise", () => {
  const fs = [mkFinding({ file: "src/pay.ts", line: 11, severity: "error", issue: "A", evidence: "const avg = total / count;" }), mkFinding({ file: "src/pay.ts", line: 12, severity: "warn", issue: "B" }), mkFinding({ file: "src/pay.ts", line: 12, severity: "warn", issue: "C" })];
  expect(excerpt(SECTION, 11)).toContain("  11 +  const avg = total / count;");
  expect(verifyPrompt("t", fs, sections)).toContain("### Achado 2");
  const checks = parseVerification('ok {"results":[{"id":1,"status":"downgraded","severity":"warn","reason":"r"},{"id":2,"status":"refuted","reason":"especulação"},{"id":3,"status":"downgraded","severity":"error"},{"id":"x","status":"refuted"},{"id":9,"status":"bogus"}]}');
  expect(checks.size).toBe(3);
  const res = applyVerification(fs, checks);
  expect(res.findings.map((f) => [f.issue, f.severity])).toEqual([["A", "warn"], ["C", "warn"]]);
  expect(res.dropped[0]!.reason).toContain("especulação");
  expect(parseVerification("not json").size).toBe(0);
});
test("verify: unavailable, unparsable or disabled verifier changes nothing; nits are never sent", async () => {
  const fs = [mkFinding({ file: "src/pay.ts", line: 11, severity: "error", issue: "A" }), mkFinding({ file: "src/pay.ts", severity: "nit", issue: "N" })];
  let prompts = 0;
  const out = await verifyFindings("t", fs, sections, async (p) => { prompts++; expect(p).not.toContain("alegação: N"); return '{"results":[{"id":1,"status":"refuted","reason":"x"}]}'; });
  expect(out.ran).toBe(true); expect(out.findings.map((f) => f.issue)).toEqual(["N"]); expect(prompts).toBe(1);
  expect((await verifyFindings("t", fs, sections, async () => { throw new Error("down"); })).findings).toEqual(fs);
  expect((await verifyFindings("t", fs, sections, async () => "garbage")).ran).toBe(false);
  process.env.REVIEW_VERIFY_ENABLED = "false";
  expect((await verifyFindings("t", fs, sections, async () => { throw new Error("must not run"); })).findings).toEqual(fs);
});

// --- decision -------------------------------------------------------------
test("decide: verdict follows the surviving findings", () => {
  const err = mkFinding({ file: "a", severity: "error", issue: "e" }), warn = mkFinding({ file: "a", severity: "warn", issue: "w" });
  expect(decide(mkVerdict({ verdict: APPROVE, summary: "ok", findings: [err] }), 0).verdict).toBe(REQUEST_CHANGES); // incoherent approve
  const cleared = decide(mkVerdict({ verdict: REQUEST_CHANGES, summary: "Diff expõe credenciais" }), 2);
  expect(cleared.verdict).toBe(APPROVE); expect(cleared.summary).not.toContain("credenciais"); expect(cleared.summary).toContain("2 alegação");
  expect(decide(mkVerdict({ verdict: REQUEST_CHANGES, summary: "s", findings: [warn] }), 1).verdict).toBe(REQUEST_CHANGES);
  expect(decide(mkVerdict({ verdict: REQUEST_CHANGES, summary: "s" }), 0).verdict).toBe(REQUEST_CHANGES); // nothing was discarded: the model's call stands
  const same = mkVerdict({ verdict: APPROVE, summary: "ok" }); expect(decide(same, 0)).toBe(same);
  expect(parseReview('{"verdict":"APPROVE","findings":[{"file":"a","evidence":"x = 1"}]}')!.findings[0]!.evidence).toBe("x = 1");
});

// --- refine (end to end, no network) --------------------------------------
test("refine: a hallucinated blocker is cleared, a real one survives with the right line", async () => {
  const v = mkVerdict({ verdict: REQUEST_CHANGES, summary: "Diff expõe credenciais", model: "m", findings: [
    mkFinding({ file: "src/pay.ts", line: 1, severity: "error", issue: "Credenciais expostas", evidence: "rcon_password = admin123" }),
    mkFinding({ file: "src/pay.ts", line: 99, severity: "error", issue: "count pode ser 0: divisão gera Infinity", evidence: "const avg = total / count;" })] });
  const kept = await refine(pr, v, sections, () => null, async () => '{"results":[{"id":1,"status":"confirmed","severity":"error","reason":"count=0"}]}');
  expect(kept.verdict).toBe(REQUEST_CHANGES);
  expect(kept.findings).toEqual([expect.objectContaining({ line: 11, severity: "error" })]);
  const onlyFake = await refine(pr, { ...v, findings: v.findings.slice(0, 1) }, sections, () => null, async () => null);
  expect(onlyFake.verdict).toBe(APPROVE); expect(onlyFake.findings).toEqual([]);
  expect(await refine(pr, v, {}, () => null, async () => null)).toBe(v); // no diff to check against: untouched
});
test("refine: sections and merge-base come from the GitHub API", async () => {
  const gh = { getFiles: async () => [{ filename: "a.ts", patch: "@@ -1 +1 @@\n+x" }, { filename: "b.png" }], compare: async (_r: string, base: string, head: string) => ({ merge_base_commit: { sha: base === pr.base.sha && head === pr.head.sha ? "c".repeat(40) : "bad" } }) } as any;
  expect(await prSections(gh, pr)).toEqual({ "a.ts": "@@ -1 +1 @@\n+x", "b.png": "" });
  expect(await mergeBaseSha(gh, pr)).toBe("c".repeat(40));
  expect(await mergeBaseSha({ compare: async () => { throw new Error("404"); } } as any, pr)).toBe("");
  expect(await mergeBaseSha({ compare: async () => ({}) } as any, pr)).toBe("");
});
