import { expect, test } from "bun:test";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { forbiddenPaths, generatedPaths, isForbiddenPath } from "../src/agents/pr_assistant/forbidden-paths.ts";
import { changedFiles, validateChanges } from "../src/agents/pr_assistant/pipeline-fixer.ts";
import { tmp } from "./helpers.ts";

// Bot fixes committed a .pyc and tried to commit node_modules, .venv and .env; those must never reach a PR.
test("isForbiddenPath flags artifacts, deps and env files", () => {
  for (const p of ["a/__pycache__/m.cpython-312.pyc", "m.pyc", "x.pyo", "node_modules/x/i.js", "web/node_modules/a", ".env", "api/.env.local", "a\\node_modules\\b", ".venv/lib/python3.13/site-packages/yt_dlp/x.py", "svc/venv/bin/activate"]) expect(isForbiddenPath(p)).toBe(true);
});
test("isForbiddenPath keeps source and env templates", () => {
  for (const p of ["src/app.py", ".env.example", "cfg/.env.sample", "docs/node_modules.md", "environment.ts", "pyc.txt", "src/venv_utils.py"]) expect(isForbiddenPath(p)).toBe(false);
  expect(forbiddenPaths([])).toEqual([]);
});
test("validateChanges rejects a fix that touches forbidden paths", async () => {
  const [ok, reason] = await validateChanges(tmp(), ["src/a.ts", "node_modules/x/i.js", ".env"]);
  expect(ok).toBe(false);
  expect(reason).toContain("node_modules/x/i.js");
  expect(reason).toContain(".env");
});

// skills#132: the pipeline fix hand-edited a generated plugins/ file; generated files must be regenerated, not patched.
test("generatedPaths flags files with a generated header or path, not hand-written code", () => {
  const dir = tmp();
  mkdirSync(join(dir, "plugins"), { recursive: true }); mkdirSync(join(dir, "src"), { recursive: true });
  writeFileSync(join(dir, "plugins/index.json"), '{"_comment": "This file is auto-generated by scripts/build.mjs"}\n');
  writeFileSync(join(dir, "src/app.ts"), "export const generated = 1;\n");
  expect(generatedPaths(dir, ["plugins/index.json", "src/app.ts", "web/dist/a.js", "missing.ts"])).toEqual(["plugins/index.json", "web/dist/a.js"]);
});
test("validateChanges rejects a fix that hand-edits a generated file", async () => {
  const dir = tmp();
  writeFileSync(join(dir, "api.pb.go"), "// Code generated by protoc-gen-go. DO NOT EDIT.\n");
  const [ok, reason] = await validateChanges(dir, ["api.pb.go"]);
  expect(ok).toBe(false);
  expect(reason).toContain("api.pb.go");
});

// nerd-watch#107: an untracked node_modules/ from the fix run vetoed the pipeline fix; only tracked forbidden edits should.
test("changedFiles ignores untracked deps and env files but keeps tracked edits and new sources", async () => {
  const dir = tmp(), sh = (...a: string[]) => Bun.spawnSync(a, { cwd: dir });
  sh("git", "init", "-q"); sh("git", "config", "user.email", "t@t"); sh("git", "config", "user.name", "t");
  writeFileSync(join(dir, "a.ts"), "1\n"); sh("git", "add", "-A"); sh("git", "commit", "-qm", "init");
  mkdirSync(join(dir, "node_modules/x"), { recursive: true }); writeFileSync(join(dir, "node_modules/x/i.js"), "1\n");
  writeFileSync(join(dir, ".env"), "A=1\n"); writeFileSync(join(dir, "a.ts"), "2\n"); writeFileSync(join(dir, "b.ts"), "3\n");
  expect((await changedFiles(dir)).sort()).toEqual(["a.ts", "b.ts"]);
});
