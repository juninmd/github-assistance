/** Deterministic triage before any model call: skip what cannot be reviewed, rank by risk, split big files instead of truncating. */
import { posix } from "node:path";

export type Unit = { path: string; text: string; part: number };
export type Skipped = { path: string; reason: string };
export type Plan = { packages: Unit[][]; skipped: Skipped[] };

const LOCKS = new Set(["package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml", "bun.lock", "bun.lockb", "cargo.lock", "poetry.lock",
  "uv.lock", "pipfile.lock", "composer.lock", "gemfile.lock", "go.sum", "pubspec.lock", "packages.lock.json", "flake.lock", "podfile.lock"]);
const GENERATED_PATH = [/\.mocks\.dart$/, /\.(g|freezed|gr|config|chopper)\.dart$/, /\.pb\.(go|ts|js|dart|cc|h)$/, /_pb2(_grpc)?\.pyi?$/, /\.generated\.\w+$/i,
  /\.designer\.cs$/i, /\.g\.cs$/, /\.min\.(js|css)$/, /\.(map|snap)$/, /(^|\/)__snapshots__\//, /(^|\/)(dist|vendor|node_modules|third_party)\//];
const GENERATED_MARK = /GENERATED CODE - DO NOT MODIFY|Code generated .{0,80}DO NOT EDIT|@generated\b|Mocks generated by Mockito|This file (is|was) (auto-?)?generated/i;
const HEAD_CHARS = 2000;
const TEST = /(^|\/)(tests?|__tests__|specs?|e2e)\/|[._-](test|spec)\.\w+$|_test\.\w+$/i;
const DOC = /\.(md|mdx|rst|txt|adoc)$|(^|\/)(docs?\/|LICENSE|CHANGELOG)/i;
const SENSITIVE = /(^|\/)\.github\/workflows\/|(^|\/)(Dockerfile|docker-compose[^/]*\.ya?ml)$|\.(tf|sql)$/i;
const CONFIG = /\.(json|ya?ml|toml|ini|cfg|lock|xml|properties|env\.example)$/i;

/** Generated by a tool (by path or by a header marker): reviewing or hand-editing it is wasted or harmful. */
export const isGenerated = (path: string, head: string) => GENERATED_PATH.some((re) => re.test(path)) || GENERATED_MARK.test(head.slice(0, HEAD_CHARS));
/** Why a file is not worth a model call, or "" when it must be reviewed. */
export function skipReason(path: string, section: string): string {
  const base = posix.basename(path).toLowerCase();
  if (LOCKS.has(base)) return "lockfile";
  if (/^(Binary files |GIT binary patch)/m.test(section)) return "binário";
  if (/^deleted file mode /m.test(section)) return "removido";
  if (isGenerated(path, section)) return "gerado";
  return "";
}
/** Lower runs first: runtime/security-sensitive code, then config, tests, docs. */
export function riskRank(path: string): number {
  if (SENSITIVE.test(path)) return 0;
  if (DOC.test(path)) return 3;
  if (TEST.test(path)) return 2;
  return CONFIG.test(path) ? 1 : 0;
}
const HUNK = /^@@ -(\d+)(?:,\d+)? \+(\d+)(?:,\d+)? @@/;
/** Split one file diff into parts ≤ budget at line boundaries; later parts get a synthetic hunk header so line numbers stay right. */
export function splitUnit(path: string, text: string, budget: number): Unit[] {
  if (text.length <= budget) return [{ path, text, part: 1 }];
  const lines = text.split(/(?<=\n)/);
  const first = lines.findIndex((l) => HUNK.test(l));
  if (first === -1) return [{ path, text: text.slice(0, budget), part: 1 }];
  const header = lines.slice(0, first).join("");
  const units: Unit[] = []; let buf = header, oldN = 0, newN = 0, body = false;
  const flush = () => { if (body) units.push({ path, text: buf, part: units.length + 1 }); buf = header; body = false; };
  for (const line of lines.slice(first)) {
    const m = HUNK.exec(line);
    if (m) { oldN = parseInt(m[1]!, 10); newN = parseInt(m[2]!, 10); }
    if (body && buf.length + line.length > budget) { flush(); if (!m) buf += `@@ -${oldN} +${newN} @@ (continuação)\n`; }
    buf += line.length > budget ? line.slice(0, budget - 1) + "\n" : line; body = true;
    if (m || line.startsWith("\\")) continue;
    if (!line.startsWith("+")) oldN++;
    if (!line.startsWith("-")) newN++;
  }
  flush();
  return units;
}
/** Reviewable files ordered by risk and packed into ≤ budget packages; everything else is reported as skipped. */
export function planPackages(sections: Record<string, string>, budget: number): Plan {
  const skipped: Skipped[] = []; const keep: [string, string][] = [];
  for (const [path, text] of Object.entries(sections)) {
    const reason = skipReason(path, text);
    if (reason) skipped.push({ path, reason }); else keep.push([path, text]);
  }
  const order = new Map(keep.map(([p], i) => [p, i]));
  keep.sort(([a], [b]) => riskRank(a) - riskRank(b) || posix.dirname(a).localeCompare(posix.dirname(b)) || order.get(a)! - order.get(b)!);
  const packages: Unit[][] = []; let cur: Unit[] = [], size = 0;
  for (const [path, text] of keep) for (const unit of splitUnit(path, text, budget)) {
    if (cur.length && size + unit.text.length > budget) { packages.push(cur); cur = []; size = 0; }
    cur.push(unit); size += unit.text.length;
  }
  if (cur.length) packages.push(cur);
  return { packages, skipped };
}
export const packageText = (units: Unit[]) => units.map((u) => u.text).join("\n");
export const packagePaths = (units: Unit[]) => [...new Set(units.map((u) => u.path))];
/** One line per skipped reason for the review summary. */
export function skippedNote(skipped: Skipped[]): string {
  const by = new Map<string, number>();
  for (const s of skipped) by.set(s.reason, (by.get(s.reason) ?? 0) + 1);
  return [...by].map(([reason, n]) => `${n} ${reason}`).join(", ");
}
